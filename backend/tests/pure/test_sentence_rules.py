"""답변 문장 분할 — 대사창 한 줄씩 넘기기용 순수 함수 (낮 화면 VN 설계 §3, 표 기반)."""

import pytest

from apps.engine.domain.entities.sentence_rules import split_sentences

CASES = [
    ("배 안 고파. 그냥 싫어.", ["배 안 고파.", "그냥 싫어."]),
    ('채연이 "배고파. 진짜." 하고 말했다.', ['채연이 "배고파. 진짜." 하고 말했다.']),  # 따옴표 안 마침표
    ("“배고파. 진짜.” 그렇게만 말했다.", ["“배고파. 진짜.” 그렇게만 말했다."]),
    ('말했다. "응." 그리고 갔다.', ["말했다.", '"응." 그리고 갔다.']),
    ("그게… 잘 모르겠어.", ["그게…", "잘 모르겠어."]),
    ("잠깐...  그건 아니야.", ["잠깐...", "그건 아니야."]),
    ("진짜?! 말도 안 돼.", ["진짜?!", "말도 안 돼."]),
    ("왜? 모르겠는데!", ["왜?", "모르겠는데!"]),
    ("아무 일도 없었어.   ", ["아무 일도 없었어."]),  # 끝 공백
    ("배 안 고파.\n그냥 싫어.", ["배 안 고파.", "그냥 싫어."]),
    ("7시 12분. 눈을 뜬다.", ["7시 12분.", "눈을 뜬다."]),
    ("1.5배는 남겼어.", ["1.5배는 남겼어."]),  # 소수점
    ('그가 "이상하다 라고 말했다. 그리고 갔다.', ['그가 "이상하다 라고 말했다.', "그리고 갔다."]),  # 짝 없는 따옴표
    ("응", ["응"]),
    ("", []),
    ("   ", []),
]


@pytest.mark.parametrize("text, expected", CASES)
def test_split_sentences(text, expected):
    assert split_sentences(text) == expected
