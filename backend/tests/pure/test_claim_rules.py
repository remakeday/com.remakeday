"""질문형 주장 판별 — 확인 화면 안내용 (테스터11 O2). 채점에는 쓰지 않는다."""

import pytest

from apps.engine.domain.entities.claim_rules import is_question_claim


@pytest.mark.parametrize("text", [
    "밥이 문제인가;;;",
    "은상과 충식은 아는사이인가???",
    "채연도 충식의 상태와 유사해지는중?",
    "채연이 아픈 걸 숨겼어？",
    "채연은 왜 배급을 남겼을까",
    "우리는 사람일까요",
    "검진에서 걸리면 이송되는가",
    "채연이 아픈가",
    "관리자가 일부러 그런 건가",
    "민석이 수첩에 적었나",
    "채연은 열이 없나요",
    "준은 번호를 알고 있니",
    "트럭이 오면 끝나냐",
    "채연이 왜 숨기는지",
    "이송된 사람이 어디로 가는지요",
    "누가 소문을 퍼뜨렸는지.",
    "관리자는 사람인지",
    "내일도 트럭이 올지",
    "채연이 아프니",
    "관리자가 알고 있습니까",
    "채연은 아프다. 그런데 왜 숨겼을까?",
    "채연이 아픈 걸 숨겼어?\"",
    "채연이 아픈 걸 숨겼어? ㅋㅋ",
    "채연이 아픈 걸 숨겼어?!",
])
def test_question_forms_are_flagged(text):
    assert is_question_claim(text)


@pytest.mark.parametrize("text", [
    "왜 그런지 모르겠다",
    "채연은 이송될까 봐 아픈 것을 숨겼다.",
    "채연은 아프니까 배급을 남겼다",
    "채연이 아프니까",
    "그렇지",
    "원인은 하나",
    "채연은 누가 볼까 봐 담요를 덮었다.",
    "무엇이 문제인지 알 것 같다.",
    "채연이 아프다",
    "우리는 돼지다!",
    "관리자는 옆 구역을 지키려 했다…",
    "소독약 냄새.",
    "트럭 소리",
    "은상의 언니",
    "",
    # 최종 리뷰 오표시 사례 — 인용 대사 속 물음표, 부정대명사, 두 음절 "~ㄴ지" 명사
    '채연이 "배고파?"라고 물었다',
    "관리자가 \"누구야?\" 하고 소리쳤다.",
    "밤에 기침한 건 누군가",
    "배급에 뭔가",
    "트럭이 오는 건 언젠가",
    "번호를 숨긴 곳은 어딘가",
    "채연이 숨긴 건 무언가",
    "채연의 편지",
    "침상 밑 먼지",
    "은상의 반지",
    "왠지",
    "은지",
])
def test_declaratives_are_not_flagged(text):
    assert not is_question_claim(text)
